CREATE DATABASE IF NOT EXISTS notesarchive CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE notesarchive;

-- Compatibility/cache table used by the existing NotesArchive app.
CREATE TABLE IF NOT EXISTS app_storage (
 storage_key VARCHAR(64) NOT NULL PRIMARY KEY,
 storage_value LONGTEXT NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(128) PRIMARY KEY, username VARCHAR(255) NULL, email VARCHAR(255) NULL,
 display_name VARCHAR(255) NULL, created_at DATETIME NULL, raw_json JSON NOT NULL,
 synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_users_email(email)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notes (
 id VARCHAR(128) PRIMARY KEY, user_id VARCHAR(128) NOT NULL, title VARCHAR(500) NULL,
 subject VARCHAR(255) NULL, content LONGTEXT NULL, created_at DATETIME NULL, updated_at DATETIME NULL,
 raw_json JSON NOT NULL, synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_notes_user(user_id), INDEX idx_notes_subject(subject)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS files (
 id VARCHAR(128) PRIMARY KEY, owner_id VARCHAR(128) NULL, name VARCHAR(500) NULL,
 mime_type VARCHAR(255) NULL, size_bytes BIGINT NULL, subject VARCHAR(255) NULL,
 created_at DATETIME NULL, raw_json JSON NOT NULL,
 synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_files_owner(owner_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_settings (
 user_id VARCHAR(128) PRIMARY KEY, settings_json JSON NOT NULL,
 synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
